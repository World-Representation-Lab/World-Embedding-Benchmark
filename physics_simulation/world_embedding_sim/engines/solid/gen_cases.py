#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path
from typing import Any


def _read_json(path: Path) -> Any:
    return json.loads(path.read_text())


def _iter_sweep_files(items: list[str]) -> list[Path]:
    if not items:
        root = Path(__file__).resolve().parents[1] / "configs"
        return sorted(root.glob("sweep_*.json"))

    out: list[Path] = []
    for raw in items:
        p = Path(raw).expanduser().resolve()
        if p.is_dir():
            out.extend(sorted(p.rglob("sweep_*.json")))
        elif p.is_file():
            out.append(p)
        else:
            raise FileNotFoundError(f"Sweep not found: {raw}")
    return sorted(dict.fromkeys(out))


def _normalize_cases(payload: Any, fallback_prefix: str) -> list[dict[str, Any]]:
    if isinstance(payload, dict) and isinstance(payload.get("cases"), list):
        rows = [x for x in payload["cases"] if isinstance(x, dict)]
    elif isinstance(payload, list):
        rows = [x for x in payload if isinstance(x, dict)]
    elif isinstance(payload, dict):
        rows = [payload]
    else:
        rows = []

    out: list[dict[str, Any]] = []
    for i, row in enumerate(rows):
        case = dict(row)
        family = str(case.get("family") or case.get("case_prefix") or fallback_prefix)
        case_prefix = str(case.get("case_prefix") or family)
        case_name = str(case.get("case_name") or f"{case_prefix}_S{i:03d}")
        geom = case.get("geometry") if isinstance(case.get("geometry"), dict) else {}
        dim = str(case.get("dim", "")).strip().upper()
        if dim not in {"2D", "3D"}:
            dim = "3D" if str(geom.get("shape_3d", "")).strip() else "2D"
        case["family"] = family
        case["case_prefix"] = case_prefix
        case["case_name"] = case_name
        case["dim"] = dim

        nonlinear = case.get("nonlinear") if isinstance(case.get("nonlinear"), dict) else {}
        if "model" not in nonlinear:
            nonlinear["model"] = "none"
        if "params" not in nonlinear or not isinstance(nonlinear.get("params"), dict):
            nonlinear["params"] = {}
        case["nonlinear"] = nonlinear

        solver = case.get("solver") if isinstance(case.get("solver"), dict) else {}
        fe = solver.get("fe") if isinstance(solver.get("fe"), dict) else {}
        if "element" not in fe:
            fe["element"] = "LagrangeP1"
        if "quadrature" not in fe:
            fe["quadrature"] = 2 if dim == "2D" else 3
        if "newton_tol" not in fe:
            fe["newton_tol"] = 1.0e-8
        if "max_iters" not in fe:
            fe["max_iters"] = 24 if dim == "2D" else 40
        if "load_steps" not in fe:
            fe["load_steps"] = int(solver.get("n_steps", 20)) if isinstance(solver.get("n_steps"), (int, float)) else 20
        solver["fe"] = fe
        case["solver"] = solver
        out.append(case)
    return out


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def _init_case_dir(case_dir: Path, case: dict[str, Any]) -> None:
    (case_dir / "system").mkdir(parents=True, exist_ok=True)
    (case_dir / "constant").mkdir(parents=True, exist_ok=True)
    (case_dir / "results").mkdir(parents=True, exist_ok=True)
    (case_dir / "postProcessing").mkdir(parents=True, exist_ok=True)

    _write_text(
        case_dir / "system" / "controlDict",
        """application solid_pde;
startTime 0;
endTime 1;
deltaT 0.05;
""",
    )
    _write_text(case_dir / "constant" / "README.txt", "Solid mechanics case generated by physics_bench_solid.\n")

    (case_dir / "case_meta.json").write_text(json.dumps(case, indent=2) + "\n")
    (case_dir / "solver_input.json").write_text(json.dumps(case, indent=2) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate solid benchmark case folders from sweep configs")
    parser.add_argument("sweeps", nargs="*", help="Sweep json files or directories")
    args = parser.parse_args()

    out_root = Path(os.environ.get("SOLID_CASES_OUT_ROOT", "./outputs/cases")).expanduser().resolve()
    force_regen = os.environ.get("FORCE_REGEN_CASES", "0").strip() not in {"", "0", "false", "False"}
    skip_raw = os.environ.get("SOLID_SKIP_FAMILIES", "").strip()
    skip_families = {x.strip().lower() for x in skip_raw.split(",") if x.strip()}

    sweeps = _iter_sweep_files(args.sweeps)
    if not sweeps:
        raise RuntimeError("No sweep files found.")

    created = 0
    skipped = 0
    skipped_family = 0
    for sweep in sweeps:
        payload = _read_json(sweep)
        fallback_prefix = sweep.stem.replace("sweep_", "")
        cases = _normalize_cases(payload, fallback_prefix=fallback_prefix)
        for case in cases:
            family = str(case["family"])
            if family.strip().lower() in skip_families:
                skipped_family += 1
                continue
            case_name = str(case["case_name"])
            case_dir = out_root / family / case_name
            if case_dir.exists() and not force_regen:
                skipped += 1
                continue
            if case_dir.exists() and force_regen:
                shutil.rmtree(case_dir)

            _init_case_dir(case_dir, case)
            created += 1

    print(
        "[solid_bench] gen_cases "
        f"sweeps={len(sweeps)} created={created} skipped={skipped} skipped_family={skipped_family} "
        f"out_root={out_root} force_regen={int(force_regen)}"
    )


if __name__ == "__main__":
    main()
